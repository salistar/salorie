type TranslationKey = keyof typeof translations['en'];

interface I18nContextType {
  language: Language;
  t: (key: TranslationKey) => string;
  setLanguage: (lang: Language) => Promise<void>;
  isRTL: boolean;
}

const I18nContext = createContext<I18nContextType | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>('en');

  useEffect(() => {
    AsyncStorage.getItem(LANG_KEY)
      .then((v) => {
        if (v === 'en' || v === 'fr' || v === 'ar') {
          setLanguageState(v);
          // Apply direction on initial load
          const isRTL = v === 'ar';
          if (I18nManager.isRTL !== isRTL) {
            I18nManager.allowRTL(isRTL);
            I18nManager.forceRTL(isRTL);
          }
        }
      })
      .catch(() => {});
  }, []);

  const setLanguage = async (lang: Language) => {
    setLanguageState(lang);
    try {
      await AsyncStorage.setItem(LANG_KEY, lang);
      // Apply RTL/LTR direction
      const isRTL = lang === 'ar';
      if (I18nManager.isRTL !== isRTL) {
        I18nManager.allowRTL(isRTL);
        I18nManager.forceRTL(isRTL);
      }
    } catch {}
  };

  const t = (key: TranslationKey): string => {
    return (translations[language] as any)[key] || (translations.en as any)[key] || key;
  };

  return (
    <I18nContext.Provider value={{ language, t, setLanguage, isRTL: language === 'ar' }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useTranslation() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useTranslation must be inside I18nProvider');
  return ctx;
}

export function getLanguageName(lang: Language): string {
  return lang === 'en' ? 'English' : lang === 'fr' ? 'Français' : 'العربية';
}
